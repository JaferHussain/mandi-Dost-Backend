namespace MandiDost.Api.Services;

public interface IMediaStorage
{
    /// <summary>Folder on disk that is served at <see cref="PublicPrefix"/>.</summary>
    string RootPath { get; }
    Task SaveAsync(string relativePath, Stream content, CancellationToken ct = default);
    void Delete(string relativePath);
}

/// <summary>
/// First release: files on the API server's disk, served at /media.
/// Before launch this should move to object storage (S3 / Cloudflare R2) behind the same interface.
/// </summary>
public class LocalMediaStorage : IMediaStorage
{
    public const string PublicPrefix = "/media";

    public LocalMediaStorage(IConfiguration config, IWebHostEnvironment env)
    {
        var configured = config["Media:RootPath"];
        RootPath = Path.GetFullPath(string.IsNullOrWhiteSpace(configured)
            ? Path.Combine(env.ContentRootPath, "App_Data", "media")
            : configured);
        Directory.CreateDirectory(RootPath);
    }

    public string RootPath { get; }

    public static string UrlFor(string relativePath) => $"{PublicPrefix}/{relativePath}";

    public async Task SaveAsync(string relativePath, Stream content, CancellationToken ct = default)
    {
        var full = FullPath(relativePath);
        Directory.CreateDirectory(Path.GetDirectoryName(full)!);
        await using var file = new FileStream(full, FileMode.CreateNew, FileAccess.Write, FileShare.None, 81920, useAsync: true);
        await content.CopyToAsync(file, ct);
    }

    public void Delete(string relativePath)
    {
        var full = FullPath(relativePath);
        if (File.Exists(full)) File.Delete(full);
    }

    // Paths are generated by the server, but guard against anything escaping the media folder anyway.
    private string FullPath(string relativePath)
    {
        var full = Path.GetFullPath(Path.Combine(RootPath, relativePath));
        if (!full.StartsWith(RootPath + Path.DirectorySeparatorChar, StringComparison.Ordinal))
            throw new InvalidOperationException("Media path escapes the media root.");
        return full;
    }
}

/// <summary>Checks the real file type from its first bytes – the client's Content-Type can't be trusted.</summary>
public static class ImageSniffer
{
    public static (string ContentType, string Extension)? Detect(ReadOnlySpan<byte> head)
    {
        if (head.Length >= 3 && head[0] == 0xFF && head[1] == 0xD8 && head[2] == 0xFF) return ("image/jpeg", ".jpg");
        if (head.Length >= 8 && head[..8].SequenceEqual(new byte[] { 0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A })) return ("image/png", ".png");
        if (head.Length >= 12 && head[..4].SequenceEqual("RIFF"u8) && head[8..12].SequenceEqual("WEBP"u8)) return ("image/webp", ".webp");
        return null;
    }
}
